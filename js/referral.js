/*
  Referral program — student side (relaunched 2026-11-22). Same file on the
  website (main) and the app (feature/pwa-phase2).

  How a student gets linked to the instructor who invited them:
    1. Invite link  instructor-profile?id=UID&ref=CODE   (or an older 16-hex token)
       → remembered on this device for 30 days (rememberReferralFromUrl)
       → applied as soon as the person is signed in: right after sign-up
         (login.html), or immediately if they're already signed in
         (instructor-profile.html, student-dashboard.html).
    2. Invite code typed by hand ("ANTONIA") at sign-up or in Settings — for
       when the link was opened inside WhatsApp's own browser and the account
       was then made somewhere else (that browser's memory isn't shared).

  Every rule (one referral per student ever, new students only, cap, program
  dates) is enforced by the registerReferral Cloud Function; this file only
  carries the code there and explains the answer.
*/
import { auth, db, doc, getDoc, functions, httpsCallable } from '../lib/firebaseClient.js';

const TOKEN_KEY = 'lb_referral_token';
const EXPIRES_KEY = 'lb_referral_expires';
const KEEP_MS = 30 * 24 * 60 * 60 * 1000;
// A link token (16 hex) or an invite code (letters/digits, as generated by the server).
const VALID = /^[A-Za-z0-9]{3,20}$/;

function store(key, value) { try { localStorage.setItem(key, value); } catch (e) {} }
function read(key) { try { return localStorage.getItem(key); } catch (e) { return null; } }

export function rememberReferralFromUrl() {
  const ref = new URLSearchParams(window.location.search).get('ref');
  if (ref && VALID.test(ref.trim())) {
    store(TOKEN_KEY, ref.trim());
    store(EXPIRES_KEY, String(Date.now() + KEEP_MS));
    return ref.trim();
  }
  return null;
}

export function getStoredReferral() {
  const token = read(TOKEN_KEY);
  const expires = parseInt(read(EXPIRES_KEY) || '0', 10);
  return token && expires > Date.now() && VALID.test(token) ? token : null;
}

export function clearStoredReferral() {
  store(TOKEN_KEY, '');
  store(EXPIRES_KEY, '0');
}

// Name of the instructor behind a link/code, for "Invited by …" (public data only).
export async function referralInstructorName(tokenOrCode) {
  try {
    const raw = String(tokenOrCode || '').trim();
    let snap = await getDoc(doc(db, 'referralTokens', raw));
    if (!snap.exists()) snap = await getDoc(doc(db, 'referralTokens', raw.toUpperCase().replace(/[^A-Z0-9]/g, '')));
    if (!snap.exists()) return null;
    const inst = await getDoc(doc(db, 'publicInstructors', snap.data().instructorId));
    return inst.exists() ? (inst.data().name || null) : null;
  } catch (e) {
    return null;
  }
}

// Outcomes that will never change for this account → forget the stored link.
const FINAL = new Set(['invalid_token', 'self_referral', 'instructor_account', 'program_ended',
  'already_referred', 'already_with_instructor', 'already_had_lessons', 'instructor_cap_reached']);

// → { success, reason?, instructorName?, message }
export async function registerReferralCode(tokenOrCode) {
  if (!auth.currentUser) return { success: false, reason: 'signed_out', message: 'Please sign in first.' };
  try {
    const call = httpsCallable(functions, 'registerReferral');
    const { data } = await call({ referralCode: String(tokenOrCode || '').trim() });
    if (data.success || FINAL.has(data.reason)) clearStoredReferral();
    return { ...data, message: referralMessage(data) };
  } catch (err) {
    console.warn('[Referral] registerReferral failed:', err && err.message);
    return { success: false, reason: 'network', message: 'Could not check the code right now. Please try again.' };
  }
}

// Applies a remembered invite link once someone is signed in. Quiet: returns null
// when there's nothing stored.
export async function applyStoredReferral() {
  const token = getStoredReferral();
  if (!token || !auth.currentUser) return null;
  return registerReferralCode(token);
}

export function referralMessage(r) {
  const who = r && r.instructorName ? r.instructorName : 'your instructor';
  switch (r && (r.success ? 'success' : r.reason)) {
    case 'success':                 return `You're connected with ${who}'s invite. Book your free trial whenever you're ready!`;
    case 'already_with_instructor': return `You're already connected with ${who}'s invite.`;
    case 'already_referred':        return 'Your account is already linked to an instructor invite. An invite can only be used once per account.';
    case 'already_had_lessons':     return 'Invite codes are for new students. Your account has already had a paid lesson.';
    case 'invalid_token':           return "We couldn't find that invite code. Please check the spelling.";
    case 'self_referral':           return "You can't use your own invite code.";
    case 'instructor_account':      return 'Invite codes are for student accounts.';
    case 'program_ended':           return 'The invite program has ended.';
    case 'instructor_cap_reached':  return `${who}'s invite has reached its limit, but you can still book lessons as normal.`;
    case 'signed_out':              return 'Please sign in first.';
    default:                        return 'Could not check the code right now. Please try again.';
  }
}

// Small brand-coloured notice at the top of the page (no dependencies).
export function showReferralNotice(text, ok = true) {
  const el = document.createElement('div');
  el.setAttribute('role', 'status');
  el.textContent = text;
  el.style.cssText = 'position:fixed;left:50%;top:calc(12px + env(safe-area-inset-top,0px));transform:translateX(-50%);z-index:20000;' +
    'max-width:min(92vw,460px);padding:12px 16px;border-radius:10px;font:600 0.92rem/1.4 "Open Sans",sans-serif;' +
    'box-shadow:0 6px 20px rgba(17,52,72,0.25);color:#fff;background:' + (ok ? '#0b6664' : '#113448') + ';';
  document.body.appendChild(el);
  setTimeout(() => { el.style.transition = 'opacity .4s'; el.style.opacity = '0'; setTimeout(() => el.remove(), 450); }, 6000);
}
