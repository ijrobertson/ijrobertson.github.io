#!/usr/bin/env python3
"""
Generates the page-specific half of css/night.css (Night mode, see js/theme.js).

Every app page styles its own cards, chips and panels in an inline <style>
block with hard-coded light colors. This reads those blocks on every page
that uses <lb-app-shell>, finds light backgrounds, dark text and light
borders, and writes night-mode overrides for exactly those selectors into
css/night.css between the GENERATED markers. Hand-written night rules live
above the markers and are kept as-is.

Re-run after changing a page's styles:   python3 scripts/build-night-css.py
"""
import colorsys
import glob
import os
import re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
NIGHT_CSS = os.path.join(ROOT, 'css', 'night.css')
START = '/* ── GENERATED by scripts/build-night-css.py — do not edit by hand ── */'
END = '/* ── END GENERATED ── */'
SCOPE = 'html[data-theme="night"]'

NAMED = {'white': '#ffffff', 'black': '#000000'}
# Page-level CSS variables (see the --pb-* palette defined on several pages)
VARS = {'--pb-surface': '#fbfbfb', '--pb-teal-dark': '#113448', '--pb-teal-deep': '#0b6664', '--pb-teal': '#20bcba',
        '--lb-color-ink-900': '#113448', '--lb-color-surface-100': '#ffffff', '--lb-color-surface-0': '#fbfbfb'}

COLOR_RE = re.compile(r'#[0-9a-fA-F]{3,8}\b|rgba?\([^)]*\)|\bwhite\b|\bblack\b|var\(--[\w-]+\)')


def to_rgba(tok):
    tok = tok.strip().lower()
    if tok.startswith('var('):
        name = tok[4:-1].split(',')[0].strip()
        tok = VARS.get(name, '')
        if not tok:
            return None
    tok = NAMED.get(tok, tok)
    if tok.startswith('#'):
        h = tok[1:]
        if len(h) in (3, 4):
            h = ''.join(c * 2 for c in h)
        if len(h) not in (6, 8):
            return None
        r, g, b = (int(h[i:i + 2], 16) / 255 for i in (0, 2, 4))
        a = int(h[6:8], 16) / 255 if len(h) == 8 else 1
        return r, g, b, a
    m = re.match(r'rgba?\(([^)]*)\)', tok)
    if m:
        parts = [p.strip() for p in re.split(r'[,\s/]+', m.group(1)) if p.strip()]
        try:
            r, g, b = (float(p) / 255 for p in parts[:3])
            a = float(parts[3].rstrip('%')) / (100 if parts[3].endswith('%') else 1) if len(parts) > 3 else 1
            return r, g, b, a
        except ValueError:
            return None
    return None


def lum(r, g, b):
    return 0.2126 * r + 0.7152 * g + 0.0722 * b


def colors_in(value):
    return [c for c in (to_rgba(t) for t in COLOR_RE.findall(value)) if c]


def night_background(value):
    """Dark replacement for a light background, or None to leave it alone."""
    cols = colors_in(value)
    if not cols or 'url(' in value:
        return None
    # Only when every color in it is light (a teal hero gradient stays as-is)
    if not all(lum(r, g, b) > 0.8 and a >= 0.5 for r, g, b, a in cols):
        return None
    r, g, b, _ = cols[0]
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    if s < 0.25 or l > 0.97:
        return 'var(--night-surface)' if l > 0.975 else 'var(--night-surface-2)'
    # Light tint (teal/green/red/yellow notice): same hue, deep and muted
    r2, g2, b2 = colorsys.hls_to_rgb(h, 0.17, min(s, 0.45))
    return '#%02x%02x%02x' % (round(r2 * 255), round(g2 * 255), round(b2 * 255))


def night_text(value):
    """Light replacement for dark text, or None to leave it alone."""
    cols = colors_in(value)
    if len(cols) != 1:
        return None
    r, g, b, a = cols[0]
    L = lum(r, g, b)
    if L > 0.6:
        return None  # already light (white text on teal etc.)
    h, l, s = colorsys.rgb_to_hls(r, g, b)
    if s < 0.2 or (0.5 < h < 0.62 and l < 0.3):   # greys and the navy ink
        return 'var(--night-text)' if L < 0.3 else 'var(--night-muted)'
    # Colored text (deep teal links, red/green status): same hue, lifted
    r2, g2, b2 = colorsys.hls_to_rgb(h, 0.68, min(max(s, 0.45), 0.75))
    return '#%02x%02x%02x' % (round(r2 * 255), round(g2 * 255), round(b2 * 255))


def light_border(value):
    cols = colors_in(value)
    return bool(cols) and all(0.7 < lum(r, g, b) < 0.99 and colorsys.rgb_to_hls(r, g, b)[2] < 0.25 for r, g, b, a in cols)


def rules(css):
    """Yield (media_or_None, selector, declarations) — flat rules and one level of @media."""
    css = re.sub(r'/\*.*?\*/', '', css, flags=re.S)
    i, n = 0, len(css)
    while i < n:
        brace = css.find('{', i)
        if brace < 0:
            return
        head = css[i:brace].strip()
        depth, j = 1, brace + 1
        while j < n and depth:
            depth += {'{': 1, '}': -1}.get(css[j], 0)
            j += 1
        body = css[brace + 1:j - 1]
        if head.startswith('@media') or head.startswith('@supports'):
            for _, sel, decl in rules(body):
                yield head, sel, decl
        elif not head.startswith('@'):
            yield None, head, body
        i = j


def scoped(selector, page):
    """Scope to night mode on this page only (js/theme.js sets data-page)."""
    scope = f'{SCOPE}[data-page="{page}"]'
    out = []
    for part in selector.split(','):
        part = part.strip()
        if not part or ':root' in part or part.startswith('html'):
            continue
        out.append(f'{scope} {part}')
    return ', '.join(out)


def build():
    pages = sorted(p for p in glob.glob(os.path.join(ROOT, '*.html')) if '<lb-app-shell' in open(p, encoding='utf-8').read())
    out, seen = [], set()
    for page in pages:
        html = open(page, encoding='utf-8').read()
        page_rules = []
        for block in re.findall(r'<style[^>]*>(.*?)</style>', html, re.S):
            for media, sel, decl in rules(block):
                if 'keyframes' in (media or ''):
                    continue
                sel_scoped = scoped(sel, os.path.basename(page)[:-len('.html')])
                if not sel_scoped:
                    continue
                props = []
                for prop, value in re.findall(r'([\w-]+)\s*:\s*([^;]+)', decl):
                    prop, value = prop.strip().lower(), value.replace('!important', '').strip()
                    # Night rules are !important (to beat inline styles), so a page's
                    # own colors that stay the same are re-stated at !important too —
                    # otherwise a broad night rule (all h3 → light text) would beat
                    # the page's more specific one (.chat-header h3 → white).
                    if prop in ('background', 'background-color', 'background-image'):
                        # The page background itself is set once in the hand-written rules
                        if re.fullmatch(r'\s*body\s*', sel):
                            continue
                        nb = night_background(value)
                        if nb:
                            props.append(f'background: {nb} !important')
                        elif value and 'url(' not in value and prop != 'background-image' and colors_in(value):
                            props.append(f'{prop}: {value} !important')
                    elif prop == 'color':
                        nt = night_text(value)
                        props.append(f'color: {nt or value} !important')
                    elif prop in ('border', 'border-top', 'border-bottom', 'border-left', 'border-right', 'border-color'):
                        if light_border(value):
                            side = '' if prop in ('border', 'border-color') else prop[len('border'):]
                            props.append(f'border{side}-color: var(--night-border) !important')
                if not props:
                    continue
                key = (media, sel_scoped, tuple(props))
                if key in seen:
                    continue
                seen.add(key)
                rule = f'{sel_scoped} {{ {"; ".join(props)}; }}'
                page_rules.append(f'{media} {{ {rule} }}' if media else rule)
        if page_rules:
            out.append(f'/* {os.path.basename(page)} */')
            out.extend(page_rules)
    out.extend(inline_rules(pages))
    return '\n'.join(out)


def inline_rules(pages):
    """Colors set in style="..." attributes (in markup or in page scripts that
    build HTML) — matched by the exact declaration text, so they apply anywhere."""
    found = {}
    for page in pages:
        html = open(page, encoding='utf-8').read()
        for style in re.findall(r'style\s*=\s*["\']([^"\'$]*)', html):
            for decl in style.split(';'):
                if ':' not in decl:
                    continue
                prop, value = (x.strip() for x in decl.split(':', 1))
                text = decl.strip()
                if not text or '"' in text:
                    continue
                prop = prop.lower()
                if prop in ('background', 'background-color'):
                    nb = night_background(value)
                    if nb:
                        found[text] = f'background: {nb} !important'
                elif prop == 'color':
                    nt = night_text(value)
                    if nt:
                        found[text] = f'color: {nt} !important'
                elif prop in ('border', 'border-top', 'border-bottom', 'border-color') and light_border(value):
                    side = '' if prop in ('border', 'border-color') else prop[len('border'):]
                    found[text] = f'border{side}-color: var(--night-border) !important'
    rules_out = ['/* inline style="..." colors (all pages) */']
    for text, decl in sorted(found.items()):
        # Match the declaration whether or not a ";" or space follows it
        rules_out.append(f'{SCOPE} [style*="{text}"] {{ {decl}; }}')
    return rules_out


def main():
    css = open(NIGHT_CSS, encoding='utf-8').read()
    generated = f'{START}\n{build()}\n{END}\n'
    if START in css:
        css = css[:css.index(START)] + generated + css[css.index(END) + len(END):].lstrip('\n')
    else:
        css = css.rstrip('\n') + '\n\n' + generated
    open(NIGHT_CSS, 'w', encoding='utf-8').write(css)
    print(f'Wrote {generated.count(chr(10)) - 2} generated lines to css/night.css')


if __name__ == '__main__':
    main()
